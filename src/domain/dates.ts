/**
 * التواريخ
 *
 * ══ المشكلة اللي الملف ده بيحلّها ══
 * كلاودفلير بتشغّل الكود بتوقيت UTC. مصر +٢ شتاءً و+٣ صيفًا.
 *
 * يعني بيعة الساعة ١ بالليل بتوقيت القاهرة، الخادم شايفها الساعة
 * ١٠ مساءً **من اليوم اللي فات**. ولو سجّلنا تاريخها من الخادم
 * مباشرةً، هتتحط على اليوم الغلط.
 *
 * محل بيقفل بعد نص الليل هيلاقي مبيعات آخر ساعتين مسجّلة إمبارح،
 * والجرد اليومي ما بيقفلش، وتقعد تدوّر على بيعة موجودة في المكان
 * الغلط.
 *
 * ══ الحل ══
 * كل تاريخ في النظام بيتحسب بتوقيت القاهرة صراحةً — في الكود هنا
 * وفي `fn_today_cairo()` في قاعدة البيانات. مصدرين متطابقين لأن
 * التاريخ بيتحدّد في المكانين حسب الحالة.
 *
 * ══ ليه نص مش كائن Date؟ ══
 * عمود `date` في قاعدة البيانات مفيهوش وقت ولا منطقة زمنية —
 * "15 أغسطس" وخلاص. لو حوّلناه لـ `Date` في جافاسكربت، هيتحط عليه
 * وقت ومنطقة، وأول ما يترجع هيتزحلق يوم في اتجاه أو التاني.
 *
 * تشبيه: تاريخ الميلاد في البطاقة مش بيتغيّر لما تسافر بلد تانية.
 * سيبه نص زي ما هو مكتوب.
 */

/** صيغة السنة-الشهر-اليوم، وهي نفس صيغة عمود `date` في بوستجرس */
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

/** أقدم تاريخ مقبول — حارس ضد غلطات الكتابة زي سنة 0202 */
const MIN_DATE = '2020-01-01';

/**
 * تاريخ النهاردة بتوقيت القاهرة، بصيغة YYYY-MM-DD.
 *
 * `en-CA` مش صدفة: دي الصيغة الوحيدة اللي بترجّع سنة-شهر-يوم
 * بالترتيب ده جاهزة، فمش محتاجين نركّبها بإيدنا.
 */
export function todayInCairo(): string {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Africa/Cairo',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date());
}

export class DateError extends Error {}

/**
 * قراءة تاريخ من مدخل المستخدم.
 *
 * بترجّع null لو المدخل فاضي — يعني "سيب الافتراضي يشتغل".
 * وبترمي DateError برسالة عربية لو المدخل موجود بس غلط.
 */
export function parseDateInput(raw: string | null | undefined): string | null {
  const text = String(raw ?? '').trim();
  if (!text) return null;

  if (!ISO_DATE.test(text)) {
    throw new DateError('صيغة التاريخ غير صحيحة.');
  }

  // فحص إن التاريخ موجود فعلاً: "2026-02-31" شكله سليم لكنه مش يوم
  const parsed = new Date(`${text}T00:00:00Z`);
  if (Number.isNaN(parsed.getTime()) || !parsed.toISOString().startsWith(text)) {
    throw new DateError('التاريخ غير موجود في التقويم.');
  }

  if (text < MIN_DATE) {
    throw new DateError('التاريخ أقدم من المسموح.');
  }

  // بضاعة ما بتدخلش المخزن بكرة، وما بتخرجش بكرة.
  // المقارنة بالنص شغّالة هنا لأن الصيغة سنة-شهر-يوم بتترتّب صح
  // أبجديًا — وده السبب التاني لاختيارها.
  if (text > todayInCairo()) {
    throw new DateError('التاريخ لا يمكن أن يكون في المستقبل.');
  }

  return text;
}

/** عرض التاريخ للمستخدم: 2026-08-15 → 15 / 08 / 2026 */
export function formatDate(iso: string | null | undefined): string {
  if (!iso || !ISO_DATE.test(iso)) return '—';
  const [year, month, day] = iso.split('-');
  return `${day} / ${month} / ${year}`;
}
